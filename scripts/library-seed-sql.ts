/**
 * Writes one idempotent SQL file that upserts the OSCE stations, Formulation
 * cases and Consulting Room library into the database, keyed by slug, with
 * the same columns the upsert-* scripts use. For pasting into the Supabase
 * SQL editor; this script itself never touches a database.
 *
 *   npx tsx --tsconfig tsconfig.json scripts/library-seed-sql.ts
 */
import { writeFileSync } from "node:fs";
import { SEED_OSCE_STATIONS } from "@/lib/practice/osce";
import { FORMULATION_CASES } from "@/lib/practice/formulation-cases";
import { SIM_LIBRARY } from "@/lib/sim/library";

const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v ?? null))}::jsonb`;

const out: string[] = ["-- Library seed (generated by scripts/library-seed-sql.ts). Safe to run more than once.", "begin;"];

for (const s of SEED_OSCE_STATIONS) {
  out.push(
    `insert into osce_stations (slug, title, task, duration_seconds, checklist, global_rating, status) values (${q(s.id)}, ${q(s.title)}, ${q(s.task)}, ${Number(s.duration_seconds)}, ${j(s.checklist)}, ${j(s.global_rating)}, 'published') on conflict (slug) do update set title = excluded.title, task = excluded.task, duration_seconds = excluded.duration_seconds, checklist = excluded.checklist, global_rating = excluded.global_rating, status = excluded.status;`,
  );
}
for (const c of FORMULATION_CASES) {
  out.push(
    `insert into formulation_cases (slug, title, prompt, factors, distractors, model_answer, status) values (${q(c.id)}, ${q(c.title)}, ${q(c.prompt)}, ${j(c.factors)}, '[]'::jsonb, ${j({ narrative: c.modelNarrative, hint: c.hint, tags: c.tags ?? null })}, 'published') on conflict (slug) do update set title = excluded.title, prompt = excluded.prompt, factors = excluded.factors, model_answer = excluded.model_answer, status = excluded.status;`,
  );
}
for (const c of SIM_LIBRARY) {
  out.push(
    `insert into sim_cases (title, slug, difficulty, case_data, status, approved, source) values (${q(c.title)}, ${q(c.slug)}, ${q(c.difficulty)}, ${j(c)}, 'published', true, 'hand_built') on conflict (slug) do update set title = excluded.title, difficulty = excluded.difficulty, case_data = excluded.case_data, status = excluded.status, approved = excluded.approved;`,
  );
}
out.push("commit;");
const path = "supabase/migrations_pending/2026_11_library_seed.sql"; // split into parts of about 400 KB for the SQL editor
writeFileSync(path, out.join("\n") + "\n");
console.log(`${path}: ${SEED_OSCE_STATIONS.length} OSCE, ${FORMULATION_CASES.length} formulation, ${SIM_LIBRARY.length} consulting room`);
