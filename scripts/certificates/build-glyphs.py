"""
Build src/lib/certificates/glyphs.generated.ts: vector outlines of the
certificate typefaces, so the on-screen preview and the PDF draw exactly the
same shapes (pdf-lib can only embed the 14 standard fonts without fontkit).

Usage (from the repo root):
  python3 scripts/certificates/build-glyphs.py <dir-with-source-serif-4-woff2>

Archivo and Silkscreen come from src/app/fonts. Source Serif 4 (OFL) comes
from the @fontsource/source-serif-4 package files (latin-400-normal,
latin-400-italic, latin-600-italic). Requires fontTools + brotli.
"""
import json, sys, os
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SERIF_DIR = sys.argv[1] if len(sys.argv) > 1 else ""
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
LATIN1 = "".join(chr(c) for c in range(0xA1, 0x100) if c not in (0xAD,))
FULL = ASCII + LATIN1 + "‘’“”•"
CAPS = "".join(chr(c) for c in range(0x20, 0x60)) + "•"

def load(path, axes=None):
    f = TTFont(path)
    if axes and "fvar" in f:
        f = instancer.instantiateVariableFont(f, axes)
    return f

def outline(font, chars):
    upm = font["head"].unitsPerEm
    s = 1000.0 / upm
    cmap = font.getBestCmap()
    gs = font.getGlyphSet()
    hmtx = font["hmtx"]
    out = {}
    for ch in chars:
        g = cmap.get(ord(ch))
        if g is None:
            continue
        pen = SVGPathPen(gs, ntos=lambda v: str(int(round(v))))
        gs[g].draw(TransformPen(pen, (s, 0, 0, -s, 0, 0)))
        out[ch] = [int(round(hmtx[g][0] * s)), pen.getCommands()]
    hhea = font["hhea"]
    os2 = font["OS/2"]
    cap = getattr(os2, "sCapHeight", 0) or 700
    return {"ascent": int(round(hhea.ascent * s)), "descent": int(round(hhea.descent * s)), "capHeight": int(round(cap * s)), "glyphs": out}

fonts = {
    "wordmark": outline(load(f"{ROOT}/src/app/fonts/archivo-var.woff2", {"wght": 900, "wdth": 125}), "VIBHA"),
    "sansWide": outline(load(f"{ROOT}/src/app/fonts/archivo-var.woff2", {"wght": 700, "wdth": 125}), CAPS),
    "sans": outline(load(f"{ROOT}/src/app/fonts/archivo-var.woff2", {"wght": 400, "wdth": 100}), FULL),
    "sansBold": outline(load(f"{ROOT}/src/app/fonts/archivo-var.woff2", {"wght": 650, "wdth": 100}), FULL),
    "pixel": outline(load(f"{ROOT}/src/app/fonts/silkscreen-400.woff2"), ASCII),
    "serif": outline(load(f"{SERIF_DIR}/source-serif-4-latin-400-normal.woff2"), FULL),
    "serifItalic": outline(load(f"{SERIF_DIR}/source-serif-4-latin-400-italic.woff2"), FULL),
    "serifDisplay": outline(load(f"{SERIF_DIR}/source-serif-4-latin-600-italic.woff2"), FULL),
}

dst = f"{ROOT}/src/lib/certificates/glyphs.generated.ts"
os.makedirs(os.path.dirname(dst), exist_ok=True)
with open(dst, "w") as fh:
    fh.write("/* eslint-disable */\n// Generated by scripts/certificates/build-glyphs.py. Do not edit by hand.\n")
    fh.write("// Outlines: Archivo and Silkscreen (src/app/fonts), Source Serif 4 (SIL Open Font License).\n")
    fh.write("// Units: 1000 per em, y grows downward from the baseline. Each glyph is [advance, path].\n")
    fh.write("export type GlyphFont = { ascent: number; descent: number; capHeight: number; glyphs: Record<string, [number, string]> };\n")
    fh.write("export const GLYPHS: Record<string, GlyphFont> = ")
    fh.write(json.dumps(fonts, separators=(",", ":"), ensure_ascii=False))
    fh.write(";\n")
print(dst, os.path.getsize(dst))
